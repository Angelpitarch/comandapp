// "917,77510000" -> 917.7751
const numero = (s?: string | null) => {
  if (!s) return null;
  const n = Number(s.trim().replace(/\./g, '').replace(',', '.'));
  return Number.isFinite(n) && n > 0 ? n : null;
};
const leer = (html: string, id: string) =>
  numero(html.match(new RegExp(`id="${id}"[\\s\\S]*?<strong[^>]*>\\s*([0-9.,]+)\\s*</strong>`))?.[1]);

Deno.serve(async (req) => {
  if (req.headers.get('x-webhook-secret') !== Deno.env.get('WEBHOOK_SECRET')) {
    return new Response('forbidden', { status: 403 });
  }
  const json = (b: unknown, status = 200) => new Response(JSON.stringify(b), { status, headers: { 'Content-Type': 'application/json' } });

  let html: string;
  try {
    const client = Deno.createHttpClient({ caCerts: [SECTIGO_OV_R36] });
    const r = await fetch('https://www.bcv.org.ve/', {
      client, headers: { 'User-Agent': 'Mozilla/5.0 (ComandApp; tasa del dia)' }, signal: AbortSignal.timeout(25_000),
    } as RequestInit & { client: Deno.HttpClient });
    if (!r.ok) return json({ error: `El BCV respondio ${r.status}` }, 502);
    html = await r.text();
  } catch (e) {
    return json({ error: 'No se pudo leer bcv.org.ve: ' + String(e) }, 502);
  }

  const usd = leer(html, 'dolar');
  const eur = leer(html, 'euro');
  const fecha = html.match(/date-display-single[^>]*content="(\d{4}-\d{2}-\d{2})/)?.[1]
    ?? html.match(/content="(\d{4}-\d{2}-\d{2})T[^"]*"[^>]*class="date-display-single"/)?.[1];
  if (!usd || !fecha) return json({ error: 'No se encontro la tasa o la fecha valor en la pagina del BCV', usd, fecha }, 502);

  const admin = createClient(Deno.env.get('SUPABASE_URL')!, Deno.env.get('SUPABASE_SERVICE_ROLE_KEY')!, {
    auth: { persistSession: false, autoRefreshToken: false },
  });
  const { data, error } = await admin.rpc('guardar_tasa_bcv', { p_fecha: fecha, p_usd: usd, p_eur: eur });
  if (error) return json({ error: error.message, usd, eur, fecha }, 422);
  return json({ ok: true, ...data });
});
